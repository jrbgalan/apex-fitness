// Helper to generate ISO dates in the past (e.g. daysAgo = 2, 5, 12, etc.)
const getDateDaysAgo = (days: number, hoursOffset = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(d.getHours() - hoursOffset);
  return d.toISOString();
};

